export function fillTemplate(body: string, vars: { name: string; id: number }) {
  const firstName = vars.name.trim().split(/\s+/)[0] || "игрок"
  return body.replaceAll("{имя}", firstName).replaceAll("{номер}", String(vars.id))
}
