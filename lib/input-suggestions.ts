/**
 * Completion of the last word the player is typing, e.g. "Анд" → "рей".
 * Only the tail is returned so it can be rendered as grey ghost text after the input value.
 */
export function suggestTail(value: string, words: readonly string[], minLength = 2) {
  if (!value || /\s$/.test(value)) return ""
  // Multi-word entries ("г. Минск") match the whole phrase after the last comma, single words the last word.
  const candidates = [value.split(",").pop()!.trimStart(), /(\S+)$/.exec(value)?.[1] ?? ""]
  for (const prefix of candidates) {
    if (prefix.length < minLength) continue
    const lower = prefix.toLowerCase()
    const word = words.find((w) => w.length > prefix.length && w.toLowerCase().startsWith(lower))
    if (word) return word.slice(prefix.length)
  }
  return ""
}
